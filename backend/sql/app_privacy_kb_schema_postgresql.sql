-- App 隐私合规检测系统知识库与扫描结果库
-- 目标数据库：PostgreSQL 13+
-- 设计原则：知识规则与扫描运行数据分离；所有规则保留来源、置信度、版本和原始数据。

BEGIN;

CREATE SCHEMA IF NOT EXISTS privacy_kb;
CREATE SCHEMA IF NOT EXISTS privacy_scan;

-- ============================================================
-- 通用更新时间触发器
-- ============================================================
CREATE OR REPLACE FUNCTION privacy_kb.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- ============================================================
-- 一、知识库导入批次
-- ============================================================
CREATE TABLE IF NOT EXISTS privacy_kb.import_batch (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file         text NOT NULL,
    source_sha256       varchar(64),
    import_mode         varchar(20) NOT NULL DEFAULT 'UPSERT',
    status              varchar(20) NOT NULL DEFAULT 'RUNNING',
    started_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at         timestamptz,
    statistics          jsonb NOT NULL DEFAULT '{}'::jsonb,
    error_message       text,
    created_by          varchar(100),
    CONSTRAINT ck_import_batch_mode CHECK (import_mode IN ('UPSERT', 'REPLACE', 'DRY_RUN')),
    CONSTRAINT ck_import_batch_status CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED', 'ROLLED_BACK'))
);
CREATE INDEX IF NOT EXISTS idx_import_batch_sha256 ON privacy_kb.import_batch(source_sha256);
CREATE INDEX IF NOT EXISTS idx_import_batch_started ON privacy_kb.import_batch(started_at DESC);

-- ============================================================
-- 二、厂商、数据来源
-- ============================================================
CREATE TABLE IF NOT EXISTS privacy_kb.vendor (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_key          varchar(160) NOT NULL UNIQUE,
    name                varchar(300) NOT NULL,
    normalized_name     varchar(300) NOT NULL,
    official_website    text,
    country_or_region   varchar(100),
    verification_status varchar(30) NOT NULL DEFAULT 'UNVERIFIED',
    raw_data            jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_vendor_verify CHECK (verification_status IN ('VERIFIED', 'PARTIAL', 'UNVERIFIED', 'PENDING_VENDOR_CONFIRM'))
);
CREATE INDEX IF NOT EXISTS idx_vendor_normalized_name ON privacy_kb.vendor(normalized_name);

DROP TRIGGER IF EXISTS trg_vendor_updated_at ON privacy_kb.vendor;
CREATE TRIGGER trg_vendor_updated_at
BEFORE UPDATE ON privacy_kb.vendor
FOR EACH ROW EXECUTE FUNCTION privacy_kb.set_updated_at();

CREATE TABLE IF NOT EXISTS privacy_kb.source (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key          varchar(180) NOT NULL UNIQUE,
    name                varchar(500) NOT NULL,
    source_type         varchar(80),
    coverage            text,
    url                 text,
    kb_usage            text,
    trust_level         varchar(20),
    maintenance_advice  text,
    source_version      varchar(100),
    published_at        timestamptz,
    fetched_at          timestamptz,
    snapshot_sha256     varchar(64),
    is_active           boolean NOT NULL DEFAULT true,
    raw_data            jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_source_type ON privacy_kb.source(source_type);
CREATE INDEX IF NOT EXISTS idx_source_url ON privacy_kb.source(url);

DROP TRIGGER IF EXISTS trg_source_updated_at ON privacy_kb.source;
CREATE TRIGGER trg_source_updated_at
BEFORE UPDATE ON privacy_kb.source
FOR EACH ROW EXECUTE FUNCTION privacy_kb.set_updated_at();

-- ============================================================
-- 三、统一软件组件知识库
-- SDK、开源库、框架、系统组件、厂商业务组件、应用模块均进入该表。
-- ============================================================
CREATE TABLE IF NOT EXISTS privacy_kb.component (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_key           varchar(180) NOT NULL UNIQUE,
    name                    varchar(500) NOT NULL,
    normalized_name         varchar(500) NOT NULL,
    english_name            varchar(500),
    vendor_id               bigint REFERENCES privacy_kb.vendor(id),
    component_kind          varchar(50) NOT NULL DEFAULT 'UNKNOWN',
    category_l1             varchar(150),
    category_l2             varchar(150),
    primary_purpose         text,
    description             text,
    attributes              text,
    license_name            varchar(200),
    sensitivity_level       varchar(20),
    confidence_level        varchar(20),
    verification_status     varchar(40) NOT NULL DEFAULT 'PENDING',
    source_type             varchar(200),
    recommended_match_rule  text,
    obfuscation_handling    text,
    false_positive_note     text,
    compliance_note         text,
    is_active               boolean NOT NULL DEFAULT true,
    record_version          integer NOT NULL DEFAULT 1,
    first_seen_at           timestamptz,
    last_verified_at        timestamptz,
    raw_data                jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at              timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_component_kind CHECK (component_kind IN (
        'SDK', 'OPEN_SOURCE_LIBRARY', 'FRAMEWORK', 'SYSTEM_COMPONENT',
        'VENDOR_COMPONENT', 'APP_MODULE', 'TOOLING', 'UNKNOWN'
    )),
    CONSTRAINT ck_component_sensitivity CHECK (
        sensitivity_level IS NULL OR sensitivity_level IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL', 'UNKNOWN')
    ),
    CONSTRAINT ck_component_confidence CHECK (
        confidence_level IS NULL OR confidence_level IN ('LOW', 'MEDIUM', 'HIGH', 'UNKNOWN')
    )
);
CREATE INDEX IF NOT EXISTS idx_component_name ON privacy_kb.component(normalized_name);
CREATE INDEX IF NOT EXISTS idx_component_vendor ON privacy_kb.component(vendor_id);
CREATE INDEX IF NOT EXISTS idx_component_kind ON privacy_kb.component(component_kind);
CREATE INDEX IF NOT EXISTS idx_component_category ON privacy_kb.component(category_l1, category_l2);
CREATE INDEX IF NOT EXISTS idx_component_active ON privacy_kb.component(is_active) WHERE is_active = true;
CREATE INDEX IF NOT EXISTS idx_component_raw_data_gin ON privacy_kb.component USING gin(raw_data);

DROP TRIGGER IF EXISTS trg_component_updated_at ON privacy_kb.component;
CREATE TRIGGER trg_component_updated_at
BEFORE UPDATE ON privacy_kb.component
FOR EACH ROW EXECUTE FUNCTION privacy_kb.set_updated_at();

CREATE TABLE IF NOT EXISTS privacy_kb.component_alias (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id        bigint NOT NULL REFERENCES privacy_kb.component(id) ON DELETE CASCADE,
    alias_name          varchar(500) NOT NULL,
    normalized_alias    varchar(500) NOT NULL,
    alias_type          varchar(30) NOT NULL DEFAULT 'OTHER',
    language_code       varchar(20),
    source_batch_id     bigint REFERENCES privacy_kb.import_batch(id),
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(component_id, normalized_alias),
    CONSTRAINT ck_component_alias_type CHECK (alias_type IN ('ENGLISH_NAME', 'PRODUCT_NAME', 'OLD_NAME', 'PACKAGE_NAME', 'OTHER'))
);
CREATE INDEX IF NOT EXISTS idx_component_alias_lookup ON privacy_kb.component_alias(normalized_alias);

-- ============================================================
-- 四、组件指纹
-- 推荐把检测引擎输出的原始特征统一映射到本表。
-- ============================================================
CREATE TABLE IF NOT EXISTS privacy_kb.component_fingerprint (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id            bigint NOT NULL REFERENCES privacy_kb.component(id) ON DELETE CASCADE,
    fingerprint_type        varchar(50) NOT NULL,
    value                   text NOT NULL,
    normalized_value        text NOT NULL,
    match_mode              varchar(20) NOT NULL DEFAULT 'EXACT',
    manifest_component_type varchar(20),
    evidence_role           varchar(20) NOT NULL DEFAULT 'SUPPORTING',
    weight                  smallint NOT NULL DEFAULT 10,
    confidence_level        varchar(20),
    is_negative             boolean NOT NULL DEFAULT false,
    is_stable               boolean,
    version_from            varchar(100),
    version_to              varchar(100),
    source_id               bigint REFERENCES privacy_kb.source(id),
    source_batch_id         bigint REFERENCES privacy_kb.import_batch(id),
    raw_data                jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at              timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(component_id, fingerprint_type, normalized_value, match_mode),
    CONSTRAINT ck_fingerprint_type CHECK (fingerprint_type IN (
        'PACKAGE_PREFIX', 'CLASS', 'MANIFEST_ACTIVITY', 'MANIFEST_SERVICE',
        'MANIFEST_RECEIVER', 'MANIFEST_PROVIDER', 'MAVEN_COORDINATE',
        'NATIVE_SO', 'RESOURCE', 'PERMISSION', 'API_SIGNATURE', 'FIELD',
        'META_DATA', 'INTENT_ACTION', 'DOMAIN', 'URL', 'STRING',
        'CERTIFICATE', 'FILE_HASH', 'METHOD_HASH', 'OTHER'
    )),
    CONSTRAINT ck_fingerprint_match_mode CHECK (match_mode IN ('EXACT', 'PREFIX', 'SUFFIX', 'CONTAINS', 'REGEX', 'HASH')),
    CONSTRAINT ck_fingerprint_role CHECK (evidence_role IN ('PRIMARY', 'SUPPORTING', 'NEGATIVE')),
    CONSTRAINT ck_fingerprint_weight CHECK (weight BETWEEN -100 AND 100)
);
CREATE INDEX IF NOT EXISTS idx_fingerprint_exact ON privacy_kb.component_fingerprint(fingerprint_type, normalized_value);
CREATE INDEX IF NOT EXISTS idx_fingerprint_component ON privacy_kb.component_fingerprint(component_id);
CREATE INDEX IF NOT EXISTS idx_fingerprint_type_mode ON privacy_kb.component_fingerprint(fingerprint_type, match_mode);
CREATE INDEX IF NOT EXISTS idx_fingerprint_prefix_text ON privacy_kb.component_fingerprint(normalized_value text_pattern_ops)
    WHERE match_mode = 'PREFIX';
CREATE INDEX IF NOT EXISTS idx_fingerprint_raw_gin ON privacy_kb.component_fingerprint USING gin(raw_data);

DROP TRIGGER IF EXISTS trg_fingerprint_updated_at ON privacy_kb.component_fingerprint;
CREATE TRIGGER trg_fingerprint_updated_at
BEFORE UPDATE ON privacy_kb.component_fingerprint
FOR EACH ROW EXECUTE FUNCTION privacy_kb.set_updated_at();

CREATE TABLE IF NOT EXISTS privacy_kb.component_relation (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_component_id bigint NOT NULL REFERENCES privacy_kb.component(id) ON DELETE CASCADE,
    child_component_id  bigint NOT NULL REFERENCES privacy_kb.component(id) ON DELETE CASCADE,
    relation_type       varchar(30) NOT NULL,
    description         text,
    source_batch_id     bigint REFERENCES privacy_kb.import_batch(id),
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(parent_component_id, child_component_id, relation_type),
    CONSTRAINT ck_component_relation_type CHECK (relation_type IN (
        'DEPENDS_ON', 'BUNDLES', 'PUSH_CHANNEL', 'REPLACES', 'VARIANT_OF',
        'FORK_OF', 'WRAPS', 'PART_OF', 'OTHER'
    )),
    CONSTRAINT ck_component_relation_self CHECK (parent_component_id <> child_component_id)
);

