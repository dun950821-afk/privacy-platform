    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_job_id         bigint NOT NULL REFERENCES privacy_scan.scan_job(id) ON DELETE CASCADE,
    package_prefix      text NOT NULL,
    identified_name     text,
    component_kind      varchar(50),
    vendor_name         text,
    category            text,
    primary_purpose     text,
    component_count     integer,
    component_type_stat jsonb NOT NULL DEFAULT '{}'::jsonb,
    matched_component_id bigint REFERENCES privacy_kb.component(id),
    risk_level          varchar(20),
    confidence_level    varchar(20),
    evidence_basis      text,
    review_focus        text,
    raw_data            jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(scan_job_id, package_prefix)
);
CREATE INDEX IF NOT EXISTS idx_package_cluster_prefix ON privacy_scan.package_cluster(package_prefix text_pattern_ops);
