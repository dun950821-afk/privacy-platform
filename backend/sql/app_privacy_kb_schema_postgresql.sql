CREATE TABLE IF NOT EXISTS privacy_scan.component_hit (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_job_id         bigint NOT NULL REFERENCES privacy_scan.scan_job(id) ON DELETE CASCADE,
    component_id        bigint NOT NULL REFERENCES privacy_kb.component(id),
    total_score         integer NOT NULL DEFAULT 0,
    confidence_level    varchar(20),
    detected_version    varchar(100),
    hit_status          varchar(20) NOT NULL DEFAULT 'CANDIDATE',
    primary_package     text,
    evidence_count      integer NOT NULL DEFAULT 0,
    raw_data            jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(scan_job_id, component_id),
    CONSTRAINT ck_component_hit_status CHECK (hit_status IN ('CONFIRMED', 'PROBABLE', 'CANDIDATE', 'REJECTED', 'WHITELISTED'))
);
CREATE INDEX IF NOT EXISTS idx_component_hit_scan ON privacy_scan.component_hit(scan_job_id, total_score DESC);

DROP TRIGGER IF EXISTS trg_component_hit_updated_at ON privacy_scan.component_hit;
