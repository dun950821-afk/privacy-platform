CREATE OR REPLACE VIEW privacy_kb.v_component_fingerprint AS
SELECT
    c.id AS component_id,
    c.name AS component_name,
    c.component_kind,
    c.category_l1,
    c.category_l2,
    v.name AS vendor_name,
    f.id AS fingerprint_id,
    f.fingerprint_type,
    f.value,
    f.normalized_value,
    f.match_mode,
    f.weight,
    f.confidence_level,
    f.evidence_role,
    f.is_negative,
    c.verification_status,
    c.is_active
FROM privacy_kb.component c
LEFT JOIN privacy_kb.vendor v ON v.id = c.vendor_id
JOIN privacy_kb.component_fingerprint f ON f.component_id = c.id;

CREATE OR REPLACE VIEW privacy_kb.v_component_privacy_profile AS
SELECT
    c.id AS component_id,
    c.name AS component_name,
    v.name AS vendor_name,
    c.component_kind,
    c.category_l1,
    c.sensitivity_level,
    COALESCE(
        jsonb_agg(DISTINCT jsonb_build_object(
            'description', d.data_description,
            'category', d.personal_info_category,
            'sensitivity', d.sensitivity_level,
            'mode', d.collection_mode,
            'purpose', d.purpose
        )) FILTER (WHERE d.id IS NOT NULL),
        '[]'::jsonb
    ) AS data_claims,
    COALESCE(
        jsonb_agg(DISTINCT jsonb_build_object(
            'permission', p.permission_name,
            'risk', p.risk_level,
            'relation', cp.relation_type
        )) FILTER (WHERE p.id IS NOT NULL),
        '[]'::jsonb
    ) AS permissions
FROM privacy_kb.component c
LEFT JOIN privacy_kb.vendor v ON v.id = c.vendor_id
LEFT JOIN privacy_kb.component_data_claim d ON d.component_id = c.id
LEFT JOIN privacy_kb.component_permission cp ON cp.component_id = c.id
LEFT JOIN privacy_kb.permission p ON p.id = cp.permission_id
GROUP BY c.id, c.name, v.name, c.component_kind, c.category_l1, c.sensitivity_level;

CREATE OR REPLACE VIEW privacy_scan.v_scan_component_result AS
SELECT
    sj.id AS scan_job_id,
    a.package_name,
    a.app_name,
    b.version_name,
    b.version_code,
    c.name AS component_name,
    v.name AS vendor_name,
    c.component_kind,
    h.total_score,
    h.confidence_level,
    h.hit_status,
    h.primary_package,
    h.evidence_count,
    c.sensitivity_level,
    c.compliance_note
FROM privacy_scan.component_hit h
JOIN privacy_scan.scan_job sj ON sj.id = h.scan_job_id
JOIN privacy_scan.app_build b ON b.id = sj.app_build_id
JOIN privacy_scan.app a ON a.id = b.app_id
JOIN privacy_kb.component c ON c.id = h.component_id
LEFT JOIN privacy_kb.vendor v ON v.id = c.vendor_id;

